import "dotenv/config";
import { Client } from "@modelcontextprotocol/sdk/client/index.js";
import { StdioClientTransport } from "@modelcontextprotocol/sdk/client/stdio.js";
const transport = new StdioClientTransport({ command: "node", args: ["scripts/metabase-mcp.mjs"], cwd: process.cwd(), env: { ...process.env } });
const client = new Client({ name: "tester", version: "1.0.0" }, { capabilities: {} });
await client.connect(transport);
const schema = await client.callTool({ name: "get_database_schema", arguments: { database_id: 2 } });
console.log("SCHEMA isError=" + Boolean(schema.isError));
console.log(schema.content.map((c) => c.text).join("\n").slice(0, 1500));
const q = await client.callTool({ name: "run_native_query", arguments: { database_id: 2, query: "SELECT 1 AS ok" } });
console.log("QUERY isError=" + Boolean(q.isError));
console.log(q.content.map((c) => c.text).join("\n").slice(0, 800));
await client.close();
